"""Independent raw-data reconstruction primitives for the frozen e2a rule.

The handover artifacts were generated by an exploratory one-second grid.  This
module names that behavior ``LEGACY_LAB_GRID_V1`` instead of treating it as the
governed execution definition.  Calendar and signal reconstruction always use
the frozen dataset lineage and physical raw trades; comparison against the lab
files is therefore able to expose, rather than inherit, their defects.
"""

